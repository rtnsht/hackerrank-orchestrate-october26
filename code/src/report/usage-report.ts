// Writes evaluation/usage_report.md from the metered usage of the final full-dataset run.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { estimateCost, llmEnabled, modelFor, PRICING, type UsageRecord } from '../mastra/llm.js';

const here = path.dirname(fileURLToPath(import.meta.url));

function fmt(n: number, d = 0): string {
  return n.toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d });
}
function usd(n: number | null): string {
  return n === null ? 'n/a (no price table entry)' : `$${n.toFixed(4)}`;
}
const approxTokens = (s: string) => Math.ceil(s.length / 4);

export function writeUsageReport(opts: {
  file: string;
  requests: number;
  seconds: number;
  usage: UsageRecord[];
  stats: Record<string, number>;
  counts: Record<string, number>;
}) {
  const { usage, requests } = opts;
  const totIn = usage.reduce((s, u) => s + u.inputTokens, 0);
  const totOut = usage.reduce((s, u) => s + u.outputTokens, 0);
  const totCalls = usage.reduce((s, u) => s + u.calls, 0);
  const costs = usage.map((u) => estimateCost(u.model, u.inputTokens, u.outputTokens));
  const totCost = costs.reduce<number>((s, c) => s + (c ?? 0), 0);
  const llmOn = { intent: llmEnabled('intent'), vision: llmEnabled('vision'), reviewer: llmEnabled('reviewer') };

  // Projection for an LLM-enabled run, from the real prompt sizes (chars/4 heuristic).
  const prompts = path.join(here, '..', 'mastra', 'prompts');
  const intentPrompt = approxTokens(fs.readFileSync(path.join(prompts, 'intent-classifier.md'), 'utf8'));
  const visionPrompt = approxTokens(fs.readFileSync(path.join(prompts, 'evidence-vision.md'), 'utf8'));
  const intentIn = intentPrompt + 120 + 150; // instructions + average request text + structured-output schema
  const intentOut = 70;
  const media = (opts.stats.pdf ?? 0) + (opts.stats.image ?? 0);
  const visionIn = visionPrompt + 1500 + 1600 + 300; // instructions + OCR text excerpt + image + schema
  const visionOut = 450;
  const intentModel = modelFor('intent');
  const visionModel = modelFor('vision');
  const projIntentCost = estimateCost(intentModel, intentIn * requests, intentOut * requests);
  const projVisionCost = estimateCost(visionModel, visionIn * media, visionOut * media);

  const lines: string[] = [];
  lines.push('# Token Usage and Cost Report');
  lines.push('');
  lines.push('This file is regenerated by `npm start` at the end of the full-dataset run that writes `output.csv`.');
  lines.push('');
  lines.push('## Final full-dataset run');
  lines.push('');
  lines.push('### Run summary');
  lines.push('');
  lines.push(`| Item | Value |`);
  lines.push(`| --- | --- |`);
  lines.push(`| Requests audited | ${fmt(requests)} |`);
  lines.push(`| Output status counts | ${Object.entries(opts.counts).map(([k, v]) => `${k}: ${v}`).join(', ')} |`);
  lines.push(`| Wall-clock time | ${opts.seconds.toFixed(1)} s |`);
  lines.push(`| Evidence files parsed | ${opts.stats.files} (SQL ${opts.stats.sql}, JSON ${opts.stats.json}, logs ${opts.stats.log}, text ${opts.stats.text}, PDF ${opts.stats.pdf}, images ${opts.stats.image}) |`);
  lines.push(`| OCR calls this run (tesseract.js, local, cache misses) | ${opts.stats.ocrCalls} |`);
  lines.push(`| LLM agents enabled | intent: ${llmOn.intent ? 'yes' : 'no'}, vision: ${llmOn.vision ? 'yes' : 'no'}, reviewer: ${llmOn.reviewer ? 'yes' : 'no'} |`);
  lines.push('');
  lines.push('### Per-model usage');
  lines.push('');
  lines.push('| Provider | Model | Agent role | Calls | Failed calls | Input tokens | Output tokens | Total tokens | Est. cost |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  if (usage.length === 0) {
    lines.push('| — | — | — | 0 | 0 | 0 | 0 | 0 | $0.0000 |');
  }
  usage.forEach((u, i) => {
    lines.push(
      `| ${u.model.split('/')[0]} | ${u.model.split('/').slice(1).join('/')} | ${u.role} | ${fmt(u.calls)} | ${fmt(u.failures)} | ${fmt(u.inputTokens)} | ${fmt(u.outputTokens)} | ${fmt(u.inputTokens + u.outputTokens)} | ${usd(costs[i])} |`,
    );
  });
  lines.push('');
  lines.push('### Overall totals');
  lines.push('');
  lines.push('| Metric | Value |');
  lines.push('| --- | --- |');
  lines.push(`| Model calls | ${fmt(totCalls)} |`);
  lines.push(`| Input tokens | ${fmt(totIn)} |`);
  lines.push(`| Output tokens | ${fmt(totOut)} |`);
  lines.push(`| Total tokens | ${fmt(totIn + totOut)} |`);
  lines.push(`| Average tokens per request | ${fmt((totIn + totOut) / Math.max(1, requests), 1)} |`);
  lines.push(`| Estimated total cost | ${usd(totCost)} |`);
  lines.push(`| Estimated cost per request | ${usd(totCost / Math.max(1, requests))} |`);
  lines.push('');
  if (totCalls === 0) {
    lines.push('No provider API key was present in the environment of this run, so every Mastra LLM agent fell back to its');
    lines.push('deterministic counterpart (multilingual intent rules, OCR + screen-aware rules). The submitted `output.csv`');
    lines.push('therefore cost **0 model tokens**. The deterministic engine is the system of record for the decision; the');
    lines.push('agents are optional language / vision front-ends whose structured outputs feed the same engine.');
    lines.push('');
  }
  lines.push('## Projection for an LLM-enabled run');
  lines.push('');
  lines.push('### Assumptions');
  lines.push('');
  lines.push(`- Intent agent (\`${intentModel}\`): 1 call per request, ~${fmt(intentIn)} input / ~${intentOut} output tokens (prompt size measured from \`src/mastra/prompts/intent-classifier.md\`).`);
  lines.push(`- Vision agent (\`${visionModel}\`): 1 call per screenshot/PDF (${media} artifacts), ~${fmt(visionIn)} input / ~${visionOut} output tokens; results are cached by file hash, so this is a one-time cost, not per request.`);
  lines.push('- Reviewer agent: off by default (`AUDIT_LLM_REVIEW=1` enables it; ~3k input / 300 output tokens per request).');
  lines.push(`- Prices (USD / 1M tokens): ${Object.entries(PRICING).filter(([m]) => m === intentModel || m === visionModel).map(([m, p]) => `${m} in ${p.input} / out ${p.output}`).join('; ')}.`);
  lines.push('');
  lines.push('### Projected totals');
  lines.push('');
  lines.push('| Model | Calls | Input tokens | Output tokens | Est. cost |');
  lines.push('| --- | --- | --- | --- | --- |');
  lines.push(`| ${intentModel} | ${fmt(requests)} | ${fmt(intentIn * requests)} | ${fmt(intentOut * requests)} | ${usd(projIntentCost)} |`);
  lines.push(`| ${visionModel} | ${fmt(media)} | ${fmt(visionIn * media)} | ${fmt(visionOut * media)} | ${usd(projVisionCost)} |`);
  const pIn = intentIn * requests + visionIn * media;
  const pOut = intentOut * requests + visionOut * media;
  const pCost = (projIntentCost ?? 0) + (projVisionCost ?? 0);
  lines.push(`| **Overall** | ${fmt(requests + media)} | ${fmt(pIn)} | ${fmt(pOut)} | ${usd(pCost)} |`);
  lines.push('');
  lines.push(`Projected average: ${fmt((pIn + pOut) / Math.max(1, requests), 1)} tokens and ${usd(pCost / Math.max(1, requests))} per request.`);
  lines.push('');
  fs.writeFileSync(opts.file, lines.join('\n'));
}
