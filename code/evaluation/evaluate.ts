// Evaluation harness: runs the real Mastra workflow (src/main.ts) on
//   1. the 32 public samples (scored against dataset/sample_output.csv), and
//   2. the participant-created custom cases (evaluation/custom-cases.ts),
// then rewrites the metrics block of evaluation/evaluation_report.md.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCsv } from '../src/core/csv.js';
import type { Step } from '../src/core/types.js';
import { CUSTOM_CASES, writeCustomDataset } from './custom-cases.js';
import { score, type Metrics, type RowPair } from './score.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const CODE = path.resolve(here, '..');
const REPO = path.resolve(CODE, '..');
const RUNS = path.join(CODE, '.runs');
fs.mkdirSync(RUNS, { recursive: true });

function runMain(args: string[], env: Record<string, string> = {}) {
  execFileSync(process.execPath, [path.join(CODE, 'node_modules', 'tsx', 'dist', 'cli.mjs'), '--no-warnings', path.join(CODE, 'src', 'main.ts'), ...args, '--no-usage-report'], {
    cwd: CODE,
    env: { ...process.env, ...env },
    stdio: ['ignore', 'ignore', 'inherit'],
  });
}

function readPred(file: string): Map<string, { status: string; steps: Step[] }> {
  return new Map(parseCsv(fs.readFileSync(file, 'utf8')).map((r) => [r.case_id, { status: r.deletion_status, steps: JSON.parse(r.steps_json) as Step[] }]));
}

// 1. public samples
const samplePred = path.join(RUNS, 'sample_predictions.csv');
runMain(['--samples', '--output', samplePred]);
const gold = parseCsv(fs.readFileSync(path.join(REPO, 'dataset', 'sample_output.csv'), 'utf8'));
const sp = readPred(samplePred);
const sampleRows: RowPair[] = gold.map((g) => ({
  case_id: g.case_id,
  goldStatus: g.deletion_status,
  goldSteps: JSON.parse(g.steps_json),
  predStatus: sp.get(g.case_id)?.status ?? 'MISSING',
  predSteps: sp.get(g.case_id)?.steps ?? [],
}));
const sampleMetrics = score(sampleRows);

// 2. custom cases
const customDir = path.join(RUNS, 'custom_dataset');
writeCustomDataset(customDir, path.join(REPO, 'dataset', 'deletion_rules.csv'));
const customPred = path.join(RUNS, 'custom_predictions.csv');
runMain(['--output', customPred], { DATASET_DIR: customDir });
const cp = readPred(customPred);
const customRows: RowPair[] = CUSTOM_CASES.map((c) => ({
  case_id: c.case_id,
  goldStatus: c.expected_status,
  goldSteps: c.expected_steps.map((s, i) => ({ step_no: i + 1, ...s }) as Step),
  predStatus: cp.get(c.case_id)?.status ?? 'MISSING',
  predSteps: cp.get(c.case_id)?.steps ?? [],
}));
const customMetrics = score(customRows);

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
function table(m: Metrics): string[] {
  return [
    '| Metric | Value |',
    '| --- | --- |',
    `| Cases | ${m.cases} |`,
    `| Case-level deletion_status accuracy | ${pct(m.statusAccuracy)} |`,
    `| Exact case match (status + full ordered steps) | ${pct(m.exactCaseMatch)} |`,
    `| Step precision | ${pct(m.stepPrecision)} |`,
    `| Step recall | ${pct(m.stepRecall)} |`,
    `| Step F1 (all 7 fields must match) | ${pct(m.stepF1)} |`,
    `| Step F1 ignoring evidence_id | ${pct(m.stepF1IgnoringEvidence)} |`,
    `| Sequence accuracy (same steps in the same order) | ${pct(m.sequenceAccuracy)} |`,
    ...Object.entries(m.fieldAccuracy).map(([k, v]) => `| Field accuracy: \`${k}\` (positional) | ${pct(v)} |`),
  ];
}
function misses(m: Metrics): string[] {
  const out: string[] = [];
  for (const c of m.perCase) {
    if (c.exact) continue;
    out.push(`- \`${c.case_id}\`: status ${c.statusOk ? 'ok' : 'WRONG'}; ${c.fn} missing / ${c.fp} extra step(s)`);
    for (const x of c.missing) out.push(`  - missing \`${x}\``);
    for (const x of c.extra) out.push(`  - extra \`${x}\``);
  }
  return out.length ? out : ['- none'];
}

const block = [
  '<!-- METRICS:START (generated by `npm run evaluate`) -->',
  '',
  '### Public samples (32 cases, `dataset/sample_output.csv`)',
  '',
  ...table(sampleMetrics),
  '',
  '#### Remaining sample differences',
  '',
  ...misses(sampleMetrics),
  '',
  `### Participant-created cases (${CUSTOM_CASES.length} cases, \`evaluation/custom-cases.ts\`)`,
  '',
  ...table(customMetrics),
  '',
  '| Case | What it checks | Expected | Predicted | Exact |',
  '| --- | --- | --- | --- | --- |',
  ...CUSTOM_CASES.map((c) => {
    const pc = customMetrics.perCase.find((x) => x.case_id === c.case_id)!;
    return `| \`${c.case_id}\` ${c.title} | ${c.checks} | ${c.expected_status} (${c.expected_steps.length} steps) | ${cp.get(c.case_id)?.status} (${cp.get(c.case_id)?.steps.length} steps) | ${pc.exact ? 'yes' : 'no'} |`;
  }),
  '',
  '#### Custom-case differences',
  '',
  ...misses(customMetrics),
  '',
  '<!-- METRICS:END -->',
].join('\n');

const reportPath = path.join(here, 'evaluation_report.md');
let report = fs.existsSync(reportPath) ? fs.readFileSync(reportPath, 'utf8') : '# Evaluation Report\n\n## Metrics\n\n<!-- METRICS:START -->\n<!-- METRICS:END -->\n';
report = report.replace(/<!-- METRICS:START[\s\S]*?<!-- METRICS:END -->/, block);
fs.writeFileSync(reportPath, report);
console.log(block);
